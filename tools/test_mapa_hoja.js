const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const page = read('play/index.html');
const game = read('play/game.js');
const map = read('play/valle-mapa.js');
const css = read('play/mapa-hoja.css');
const geo = JSON.parse(read('data/valle-geo.json').replace(/^window\.VALLE_GEO=/, '').replace(/;$/, ''));
assert.ok(!map.includes('if (sameTown) continue'));
assert.ok(map.includes('park.name'));
assert.ok(geo.parques.some(item => item.name === 'Parque de Envigado'));
assert.ok(geo.parques.some(item => item.name === 'Las Palmas'));
const open = game.slice(game.indexOf('function openCityMap'), game.indexOf('function closeCityMap'));
assert.ok(!open.includes('if (!started) return'));
assert.ok(game.includes('fillMapPlaces'));
assert.ok(game.includes('VALLE_GEO.parques'));
assert.ok(page.includes('✕ Cerrar'));
assert.ok(page.includes('mapa-hoja.css?v=ruta-mina'));
assert.ok(page.includes('valle-mapa.js?v=seguir-amigo'));
assert.ok(game.includes('Ir a la mina'));
assert.ok(game.includes("t: 'ir_mina'"));
assert.ok(game.includes('S.mounted && e'));
assert.ok(map.includes("ctx.fillText('Mina'"));
assert.ok(css.includes('max-height: min(42dvh, 360px)'));
assert.ok(css.includes('touch-action: pan-y'));
assert.ok(css.includes('z-index: 90'));
assert.ok(css.includes('body:not(.in-game) #hud-mapa'));
assert.ok(game.includes("if (e.clientY - y0 > 48) closeCityMap()"));
assert.ok(game.includes("if(e.target===$('#city-map'))closeCityMap()"));
assert.ok(game.includes("e.key==='Escape' && !$('#city-map').hidden"));
